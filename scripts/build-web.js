// Builds the phone app into web-dist/: the desktop pages (src/renderer) with web/api.js standing in for the Electron
// side, the libraries they load, an install manifest and a service worker so it keeps working offline.
// The folder is a plain static site; .github/workflows/phone.yml publishes it on GitHub Pages.
// Usage: node scripts/build-web.js   then, to try it: npx http-server web-dist (or any static server)
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'web-dist');
const mod = (...p) => path.join(ROOT, 'node_modules', ...p);

fs.rmSync(OUT, { recursive: true, force: true });
const copy = (src, dest, filter) => fs.cpSync(src, path.join(OUT, dest), { recursive: true, filter: filter || (() => true) });

copy(path.join(ROOT, 'src', 'renderer'), '.');
copy(path.join(ROOT, 'src', 'assets'), 'assets');
copy(path.join(ROOT, 'build', 'icon-mac.png'), 'assets/icon-1024.png');
copy(path.join(ROOT, 'web'), 'web');
copy(mod('leaflet', 'dist'), 'lib/leaflet', (f) => !f.endsWith('.map'));
copy(mod('chart.js', 'dist', 'chart.umd.js'), 'lib/chartjs/chart.umd.js');
copy(mod('@mdi', 'font', 'css', 'materialdesignicons.min.css'), 'lib/mdi/css/materialdesignicons.min.css');
copy(mod('@mdi', 'font', 'fonts', 'materialdesignicons-webfont.woff2'), 'lib/mdi/fonts/materialdesignicons-webfont.woff2');
copy(mod('pdfjs-dist', 'build', 'pdf.min.mjs'), 'vendor/pdfjs/pdf.min.mjs');
copy(mod('pdfjs-dist', 'build', 'pdf.worker.min.mjs'), 'vendor/pdfjs/pdf.worker.min.mjs');
copy(mod('scrypt-js', 'scrypt.js'), 'lib/scrypt/scrypt.js');

// The icon font's CSS also lists .eot/.woff/.ttf; browsers use the first format they support, which is woff2.
const rewrite = (rel, fn) => { const f = path.join(OUT, rel); fs.writeFileSync(f, fn(fs.readFileSync(f, 'utf8'))); };
const local = (s) => s.replace(/app:\/\/lib\//g, 'lib/').replace(/app:\/\/assets\//g, 'assets/');
rewrite('styles.css', local);
rewrite('lib/printdoc.js', local);
rewrite('index.html', (s) => local(s)
  .replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/, `<meta http-equiv="Content-Security-Policy" content="default-src 'self'; img-src 'self' data: blob:; style-src 'self' 'unsafe-inline'; font-src 'self'; script-src 'self'; connect-src 'self' blob: https://api.postcodes.io; frame-src 'self' blob:; worker-src 'self' blob:">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#b3261e">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="assets/icon-256.png">`)
  .replace('<script type="module" src="app.js"></script>', '<script src="lib/scrypt/scrypt.js"></script>\n<script type="module" src="web/api.js"></script>\n<script type="module" src="app.js"></script>'));

fs.writeFileSync(path.join(OUT, 'manifest.webmanifest'), JSON.stringify({
  name: 'Holdfast Emergency Preparation System',
  short_name: 'Holdfast',
  description: 'Your household emergency plan and document vault, offline.',
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: '#1e2328',
  theme_color: '#b3261e',
  icons: [
    { src: 'assets/icon-256.png', sizes: '256x256', type: 'image/png' },
    { src: 'assets/icon-1024.png', sizes: '1024x1024', type: 'image/png', purpose: 'any' },
  ],
}, null, 1));

// Every file goes in the offline cache. The cache name changes whenever any file does, so phones pick up updates.
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else files.push(path.relative(OUT, p).split(path.sep).join('/'));
  }
})(OUT);
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(OUT, f)));
const version = hash.digest('hex').slice(0, 12);
fs.writeFileSync(path.join(OUT, 'sw.js'), `// Generated by scripts/build-web.js. Serves the app from the cache so it opens with no signal.
const CACHE = 'holdfast-${version}';
const FILES = ${JSON.stringify(['./', ...files])};
self.addEventListener('install', (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener('activate', (e) => e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`);
const bytes = files.reduce((a, f) => a + fs.statSync(path.join(OUT, f)).size, 0);
console.log(`web-dist: ${files.length + 1} files, ${(bytes / 1048576).toFixed(1)} MB, cache ${version}`);
